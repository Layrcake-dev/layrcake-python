def camel(name: str) -> str:
    parts = re.split(r"[^0-9A-Za-z]+", name)
    out = "".join(p[:1].upper() + p[1:] for p in parts if p)
    if out and out[0].isdigit():
        out = "N" + out
    return out


def py_str(value: str) -> str:
    return json.dumps(value, ensure_ascii=False)


def doc_text(text: str) -> str:
    return text.replace("\\", "\\\\").replace('"""', '\\"\\"\\"').strip()


def wrap(text: str, width: int, indent: str) -> list[str]:
    words = text.split()
    lines: list[str] = []
    line = ""
    for word in words:
        if line and len(indent) + len(line) + 1 + len(word) > width:
            lines.append(indent + line)
            line = word
        else:
            line = f"{line} {word}" if line else word
    if line:
        lines.append(indent + line)
    return lines


def canonical(schema: Any) -> str:
    """A hash key for a schema's shape, ignoring documentation-only keywords."""

    def strip(x: Any) -> Any:
        if isinstance(x, dict):
            return {
                k: strip(v)
                for k, v in sorted(x.items())
                if k not in ("description", "example", "examples", "$schema", "title", "default")
            }
        if isinstance(x, list):
            return [strip(v) for v in x]
        return x

    return hashlib.sha256(json.dumps(strip(schema), sort_keys=True).encode()).hexdigest()


@dataclass
class TypeDef:
    name: str
    code: str


@dataclass
class TypeGen:
    defs: list[TypeDef] = field(default_factory=list)
    by_hash: dict[str, str] = field(default_factory=dict)
    used: set[str] = field(default_factory=set)
    dry_run_names: set[str] = field(default_factory=set)

    def unique(self, name: str) -> str:
        if name not in self.used:
            self.used.add(name)
            return name
        i = 2
        while f"{name}{i}" in self.used:
            i += 1
        self.used.add(f"{name}{i}")
        return f"{name}{i}"

    def annotate(self, schema: Any, name: str, *, input_side: bool = False) -> str:
        """Return a type expression for schema, defining named types as needed."""
        if not isinstance(schema, dict) or not schema:
            return "Any"
        if "const" in schema:
            return f"Literal[{py_literal(schema['const'])}]"
        if "enum" in schema:
            return "Literal[" + ", ".join(py_literal(v) for v in schema["enum"]) + "]"
        for key in ("anyOf", "oneOf"):
            if key in schema:
                return self.union(schema[key], name, schema, input_side=input_side)
        t = schema.get("type")
        if isinstance(t, list):
            members = [self.annotate({**schema, "type": x}, name, input_side=input_side) for x in t]
            return union_expr(members)
        if t == "string":
            return "str"
        if t == "integer":
            return "int"
        if t == "number":
            return "float"
        if t == "boolean":
            return "bool"
        if t == "null":
            return "None"
        if t == "array":
            items = schema.get("items")
            inner = self.annotate(items, name + "Item", input_side=input_side) if isinstance(items, dict) else "Any"
            return f"List[{inner}]"
        if t == "object" or "properties" in schema:
            props = schema.get("properties")
            if not props:
                addl = schema.get("additionalProperties")
                if isinstance(addl, dict) and addl:
                    return f"Dict[str, {self.annotate(addl, name + 'Value', input_side=input_side)}]"
                return "Dict[str, Any]"
            return self.typed_dict(schema, name, input_side=input_side)
        return "Any"

    def union(self, variants: list[Any], name: str, parent: dict[str, Any], *, input_side: bool) -> str:
        suffixes = variant_suffixes(variants)
        members = [self.annotate(v, name + sfx, input_side=input_side) for v, sfx in zip(variants, suffixes)]
        return union_expr(members)

    def typed_dict(self, schema: dict[str, Any], name: str, *, input_side: bool) -> str:
        key = canonical(schema)
        if key in self.by_hash:
            return self.by_hash[key]
        name = self.unique(NAME_OVERRIDES.get(name, name))
        self.by_hash[key] = name
        props: dict[str, Any] = schema["properties"]
        if isinstance(props.get("dry_run"), dict) and props["dry_run"].get("const") is True:
            self.dry_run_names.add(name)
        required = set(schema.get("required", []))
        fields: list[tuple[str, str, bool, str]] = []
        for prop, sub in props.items():
            child = PREFERRED_NAMES.get(prop) if not input_side and PREFERRED_NAMES.get(prop) not in self.used else None
            child_name = child or (name + camel(prop))
            annotation = self.annotate(sub, child_name, input_side=input_side)
            desc = sub.get("description", "") if isinstance(sub, dict) else ""
            fields.append((prop, annotation, prop in required, desc))
        self.defs.append(TypeDef(name, render_typed_dict(name, fields, schema.get("description", ""))))
        return name


def variant_suffixes(variants: list[Any]) -> list[str]:
    """Name each member of a union by what tells it apart from its siblings.

    In order: a dry-run plan is DryRun; a single-valued discriminator such as
    status="sent" gives Sent; the one other member beside a dry run is Data;
    a required property no sibling has gives its name; otherwise VariantN.
    """
    props_of = [(v.get("properties") or {}) if isinstance(v, dict) else {} for v in variants]
    structured = [
        i for i, v in enumerate(variants) if isinstance(v, dict) and (props_of[i] or "anyOf" in v or "oneOf" in v)
    ]
    if len(structured) == 1:
        # An object beside null or a scalar keeps its parent's name.
        return [""] * len(variants)
    suffixes: list[str] = []
    for i, variant in enumerate(variants):
        props = props_of[i]
        suffix = ""
        if not isinstance(variant, dict):
            suffix = f"Variant{i + 1}"
        elif isinstance(props.get("dry_run"), dict) and props["dry_run"].get("const") is True:
            suffix = "DryRun"
        elif not props and "anyOf" not in variant and "oneOf" not in variant:
            suffix = "" if variant.get("type") != "object" else f"Variant{i + 1}"
        else:
            for disc in DISCRIMINATORS:
                sub = props.get(disc)
                if not isinstance(sub, dict):
                    continue
                if isinstance(sub.get("const"), str):
                    suffix = camel(sub["const"])
                    break
                enum = sub.get("enum")
                if isinstance(enum, list) and len(enum) == 1 and isinstance(enum[0], str):
                    suffix = camel(enum[0])
                    break
        suffixes.append(suffix)
    dry = [i for i, sfx in enumerate(suffixes) if sfx == "DryRun"]
    unnamed = [
        i
        for i, v in enumerate(variants)
        if suffixes[i] == "" and isinstance(v, dict) and (props_of[i] or "anyOf" in v or "oneOf" in v)
    ]
    if len(dry) == 1 and len(unnamed) == 1:
        suffixes[unnamed[0]] = "Data"
    for i in unnamed:
        if suffixes[i]:
            continue
        own = set(variants[i].get("required") or [])
        others: set[str] = set()
        for j, p in enumerate(props_of):
            if j != i:
                others |= set(p)
        unique = [r for r in (variants[i].get("required") or []) if r in own - others]
        suffixes[i] = camel(unique[0]) if unique else f"Variant{i + 1}"
    taken: set[str] = set()
    for i, sfx in enumerate(suffixes):
        if not sfx:
            continue
        if sfx in taken:
            n = 2
            while f"{sfx}{n}" in taken:
                n += 1
            suffixes[i] = f"{sfx}{n}"
        taken.add(suffixes[i])
    return suffixes


def py_literal(value: Any) -> str:
    if isinstance(value, bool):
        return "True" if value else "False"
    if value is None:
        return "None"
    if isinstance(value, (int, float)):
        return repr(value)
    return py_str(str(value))


def union_expr(members: list[str]) -> str:
    flat: list[str] = []

    def add(member: str) -> None:
        if member.startswith("Union[") and member.endswith("]"):
            for part in split_top(member[len("Union[") : -1]):
                add(part)
        elif member.startswith("Optional[") and member.endswith("]"):
            add(member[len("Optional[") : -1])
            add("None")
        elif member not in flat:
            flat.append(member)

    for m in members:
        add(m)
    if "Any" in flat:
        return "Any"
    has_none = "None" in flat
    rest = [m for m in flat if m != "None"]
    literals = [m for m in rest if m.startswith("Literal[")]
    if len(literals) > 1:
        inner: list[str] = []
        for lit in literals:
            for part in split_top(lit[len("Literal[") : -1]):
                if part not in inner:
                    inner.append(part)
        first = rest.index(literals[0])
        rest = [m for m in rest if m not in literals]
        rest.insert(first, "Literal[" + ", ".join(inner) + "]")
    if not rest:
        return "None"
    core = rest[0] if len(rest) == 1 else "Union[" + ", ".join(rest) + "]"
    return f"Optional[{core}]" if has_none else core


def members_of(expr: str) -> list[str]:
    """The top-level members of a Union[...] expression, or the expression itself."""
    if expr.startswith("Union[") and expr.endswith("]"):
        return split_top(expr[len("Union[") : -1])
    return [expr]


def one_line(text: str) -> str:
    """The first sentence of the first paragraph, the way the TypeScript SDK reads it."""
    first = re.split(r"\n\s*\n", text)[0]
    first = re.sub(r"\s+", " ", first).strip()
    match = re.match(r"^(.+?[.!?])(\s|$)", first)
    return (match.group(1) if match else first).strip()


def split_top(text: str) -> list[str]:
    parts: list[str] = []
    depth = 0
    current = ""
    in_str = False
    prev = ""
    for ch in text:
        if ch == '"' and prev != "\\":
            in_str = not in_str
        if not in_str:
            if ch == "[":
                depth += 1
            elif ch == "]":
                depth -= 1
            elif ch == "," and depth == 0:
                parts.append(current.strip())
                current = ""
                prev = ch
                continue
        current += ch
        prev = ch
    if current.strip():
        parts.append(current.strip())
    return parts


def render_typed_dict(name: str, fields: list[tuple[str, str, bool, str]], description: str) -> str:
    required = [f for f in fields if f[2]]
    optional = [f for f in fields if not f[2]]
    functional = any(not f[0].isidentifier() or keyword.iskeyword(f[0]) for f in fields)
    lines: list[str] = []
    if functional:
        # Some keys (such as "from") are Python keywords, so the class syntax
        # cannot name them. The functional syntax can.
        def functional_dict(td_name: str, items: list[tuple[str, str, bool, str]], total: bool) -> list[str]:
            block = [f"{td_name} = TypedDict(", f"    {py_str(td_name)},", "    {"]
            block.extend(f"        {py_str(f[0])}: {f[1]}," for f in items)
            block.append("    },")
            if not total:
                block.append("    total=False,")
            block.append(")")
            return block

        if required and optional:
            lines.extend(functional_dict(f"_{name}Required", required, True))
            lines.extend(functional_dict(f"_{name}Optional", optional, False))
            lines.append("")
            lines.append("")
            lines.append(f"class {name}(_{name}Required, _{name}Optional):")
            lines.append(f'    """{doc_text(description)}"""' if description else "    pass")
        else:
            lines.extend(functional_dict(name, fields, bool(required)))
        return "\n".join(lines)

    def body(items: list[tuple[str, str, bool, str]]) -> list[str]:
        out: list[str] = []
        for prop, annotation, _req, desc in items:
            out.append(f"    {prop}: {annotation}")
            if desc:
                out.append(f'    """{doc_text(desc)}"""')
                out.append("")
        while out and out[-1] == "":
            out.pop()
        return out

    if required and optional:
        lines.append(f"class _{name}Required(TypedDict):")
        lines.extend(body(required))
        lines.append("")
        lines.append("")
        lines.append(f"class {name}(_{name}Required, total=False):")
        if description:
            lines.append(f'    """{doc_text(description)}"""')
            lines.append("")
        lines.extend(body(optional))
    else:
        total = "" if required else ", total=False"
        lines.append(f"class {name}(TypedDict{total}):")
        if description:
            lines.append(f'    """{doc_text(description)}"""')
            lines.append("")
        lines.extend(body(fields))
    return "\n".join(lines)


@dataclass
class Param:
    name: str  # wire name
    py_name: str
    annotation: str
    required: bool
    description: str
    location: str  # body, query, path


@dataclass
class Operation:
    op_id: str
    method: str
    path: str
    summary: str
    headline: str
    description: str
    params: list[Param]
    idempotency: str  # none, optional, required
    read_only: bool
    envelope: bool
    response_kind: str  # json, text, empty
    result_type: str
    has_body: bool
    tag: str
    live_type: str = ""
    """Result type when dry_run is not set. Empty when the call has no dry run."""
    dry_type: str = ""
    """Result type when dry_run is True."""


def json_body(op: dict[str, Any]) -> dict[str, Any] | None:
    rb = op.get("requestBody")
    if not rb:
        return None
    schema = rb.get("content", {}).get("application/json", {}).get("schema")
    return schema if isinstance(schema, dict) else None


def response_schemas(op: dict[str, Any]) -> list[tuple[str, str, dict[str, Any] | None]]:
    out = []
    for code, resp in op.get("responses", {}).items():
        if not (code.startswith("2")):
            continue
        content = resp.get("content") or {}
        if "application/json" in content:
            out.append((code, "json", content["application/json"].get("schema")))
        elif "text/csv" in content:
            out.append((code, "text", None))
        else:
            out.append((code, "empty", None))
    return out


def envelope_branches(schema: dict[str, Any]) -> list[dict[str, Any]] | None:
    """Return the `{result, layrcake}` branches of a body schema, or None."""
    branches = schema.get("anyOf") or schema.get("oneOf") or [schema]
    if all(isinstance(b, dict) and "result" in (b.get("properties") or {}) for b in branches):
        return branches
    return None


def path_param_name(path: str, name: str) -> str:
    if name != "id":
        return name
    segments = path.strip("/").split("/")
    idx = segments.index("{id}")
    resource = segments[idx - 1]
    resource = resource[:-1] if resource.endswith("s") else resource
    return f"{resource}_id"


def build(spec: dict[str, Any], summaries: dict[str, str]) -> tuple[str, str, str, str]:
    gen = TypeGen()
    ops: list[Operation] = []
    aliases: list[str] = []
    public_names: list[str] = []

    for path, item in spec["paths"].items():
        for method, op in item.items():
            if not isinstance(op, dict) or "operationId" not in op:
                continue
            op_id: str = op["operationId"]
            cname = camel(op_id)
            params: list[Param] = []
            idempotency = "none"
            for prm in [*op.get("parameters", []), *SUPPLEMENTAL_QUERY.get(op_id, [])]:
                loc = prm["in"]
                if loc == "header" and prm["name"].lower() == "idempotency-key":
                    idempotency = "required" if prm.get("required") else "optional"
                    continue
                if loc == "header":
                    continue
                py_name = path_param_name(path, prm["name"]) if loc == "path" else prm["name"]
                ann = gen.annotate(prm.get("schema", {}), cname + camel(py_name) + "Param", input_side=True)
                params.append(
                    Param(
                        prm["name"],
                        py_name,
                        ann,
                        bool(prm.get("required")) or loc == "path",
                        prm.get("description", ""),
                        loc,
                    )
                )
            body = json_body(op)
            has_body = body is not None
            if body is not None and body.get("properties"):
                required = set(body.get("required", []))
                body_fields = {k: v for k, v in body["properties"].items() if (op_id, k) not in SKIPPED_BODY_FIELDS}
                params_td = gen.typed_dict(
                    {
                        **body,
                        "properties": body_fields,
                        "required": [r for r in body.get("required", []) if r in body_fields],
                    },
                    cname + "Params",
                    input_side=True,
                )
                public_names.append(params_td)
                for prop, sub in body_fields.items():
                    ann = gen.annotate(sub, cname + "Params" + camel(prop), input_side=True)
                    if ann.startswith("List["):
                        ann = "Sequence[" + ann[len("List[") :]
                    py_name = prop + "_" if keyword.iskeyword(prop) else prop
                    params.append(Param(prop, py_name, ann, prop in required, sub.get("description", ""), "body"))
            reserved = {"idempotency_key", "extra_headers", "extra_query", "extra_body", "timeout", "self"}
            clash = [p.py_name for p in params if p.py_name in reserved]
            if clash:
                raise SystemExit(f"{op_id}: parameter names clash with SDK options: {clash}")

            # Response and result types.
            envelope = False
            result_members: list[str] = []
            response_kind = "json"
            for code, kind, schema in response_schemas(op):
                if kind == "text":
                    response_kind = "text"
                    result_members.append("str")
                    continue
                if kind == "empty" or schema is None:
                    if op_id in SUPPLEMENTAL_RESPONSES:
                        result_members.append(gen.annotate(SUPPLEMENTAL_RESPONSES[op_id], cname + "Result"))
                    else:
                        response_kind = "empty" if code == "200" else response_kind
                        result_members.append("Any")
                    continue
                branches = envelope_branches(schema)
                if branches is not None:
                    envelope = True
                    for b in branches:
                        result_members.append(gen.annotate(b["properties"]["result"], cname + "Result"))
                        meta = (b.get("properties") or {}).get("layrcake")
                        if isinstance(meta, dict):
                            gen.annotate(meta, "LayrcakeMeta")
                else:
                    # 202 bodies are shared by every action a person approves.
                    type_name = cname + "Result" if code == "200" else "Accepted"
                    result_members.append(gen.annotate(schema, type_name))
            override = RESPONSE_OVERRIDES.get(op_id, {})
            if override.get("wrapped") and envelope:
                raise SystemExit(f"{op_id}: the spec now describes the envelope; drop its wrapped override")
            if "result" in override:
                result_members = [override["result"]]
            if override.get("wrapped"):
                response_kind = "json"
            # Every JSON body is unwrapped by shape at runtime, except flat ones.
            envelope = response_kind != "text" and not override.get("flat")
            if response_kind == "empty":
                result_members = ["Any"]
            result_expr = union_expr(result_members) if result_members else "Any"
            alias = f"{cname}Result"
            if result_expr == alias:
                result_type = alias
            else:
                if alias in gen.used:
                    raise SystemExit(f"{op_id}: {alias} is already a type name")
                gen.used.add(alias)
                aliases.append(f"{alias} = {result_expr}")
                result_type = alias

            # Calls with a dry run get typed overloads: dry_run=True returns the plan.
            live_type = dry_type = ""
            members = members_of(result_expr)
            dry = [m for m in members if m in gen.dry_run_names]
            live = [m for m in members if m not in gen.dry_run_names]
            if dry and live and any(p.name == "dry_run" for p in params):
                dry_type = union_expr(dry)
                live_type = union_expr(live)

            spec_summary = (op.get("summary") or op.get("description") or "").strip()
            summary = spec_summary or summaries.get(op_id, "").strip()
            if not summary:
                raise SystemExit(f"{op_id}: no summary in the spec or scripts/fallback_summaries.json")
            # Spec summaries can run long, so the headline is their first
            # sentence. A fallback summary is already one line.
            headline = one_line(spec_summary) if spec_summary else summary
            ops.append(
                Operation(
                    op_id=op_id,
                    method=method.upper(),
                    path=path,
                    summary=summary,
                    headline=headline,
                    description=op.get("description", "") if op.get("summary") else "",
                    params=params,
                    idempotency=idempotency,
                    read_only=method.upper() == "GET" or op_id in READ_ONLY_POSTS,
                    envelope=envelope,
                    response_kind=response_kind,
                    result_type=result_type,
                    has_body=has_body,
                    tag=(op.get("tags") or [""])[0],
                    live_type=live_type,
                    dry_type=dry_type,
                )
            )

    # The error body.
    error_schema = None
    for item in spec["paths"].values():
        for op in item.values():
            for code, resp in op.get("responses", {}).items():
                sch = (resp.get("content") or {}).get("application/json", {}).get("schema")
                if code[0] in "45" and isinstance(sch, dict) and "error" in (sch.get("properties") or {}):
                    error_schema = sch
                    break
            if error_schema:
                break
        if error_schema:
            break
    if error_schema is None:
        raise SystemExit("no error schema found")
    codes = error_schema["properties"]["error"]["properties"]["code"]["enum"]
    aliases.append("ErrorCode = Literal[" + ", ".join(py_str(c) for c in codes) + "]")
    gen.annotate(error_schema["properties"]["error"], "ErrorObject")
    gen.annotate(error_schema, "ErrorBody")

    types_py = render_types(spec, gen, aliases)
    operations_py = render_operations(ops, codes)
    methods_py = render_methods(ops)
    return types_py, operations_py, methods_py, render_readme_table(ops)


def typing_import(code: str, always: tuple[str, ...] = ()) -> str:
    """The `from typing import ...` line for exactly the names code uses."""
    candidates = (
        "TYPE_CHECKING",
        "Any",
        "Dict",
        "List",
        "Literal",
        "Mapping",
        "Optional",
        "Sequence",
        "TypedDict",
        "Union",
        "overload",
    )
    names = {tok.string for tok in tokenize.generate_tokens(io.StringIO(code).readline) if tok.type == tokenize.NAME}
    used = [n for n in candidates if n in always or n in names]
    return "from typing import " + ", ".join(used)


def finish(out: list[str]) -> str:
    code = "\n".join(out)
    return code.replace("@@TYPING_IMPORT@@", typing_import(code))


def render_types(spec: dict[str, Any], gen: TypeGen, aliases: list[str]) -> str:
    info = spec.get("info", {})
    out = [HEADER.rstrip(), f"# Source: {info.get('title', 'API')} {info.get('version', '')}".rstrip(), ""]
    out.append('"""Request and response types for the Layrcake API."""')
    out.append("")
    out.append("@@TYPING_IMPORT@@")
    out.append("")
    names = [d.name for d in gen.defs] + [a.split(" = ", 1)[0] for a in aliases]
    out.append("__all__ = [")
    out.extend(f"    {py_str(n)}," for n in sorted(names))
    out.append("]")
    for d in gen.defs:
        out.append("")
        out.append("")
        out.append(d.code)
    out.append("")
    out.append("")
    for a in aliases:
        out.append(a)
    out.append("")
    return finish(out)


def render_operations(ops: list[Operation], codes: list[str]) -> str:
    out = [HEADER.rstrip(), "", '"""Static facts about each API operation."""', ""]
    out.append("from .._operation import OperationSpec")
    out.append("")
    out.append("API_ERROR_CODES = (")
    out.extend(f"    {py_str(c)}," for c in codes)
    out.append(")")
    out.append('"""Every error code the API declares. The server may add codes later."""')
    out.append("")
    for op in ops:
        const = op.op_id.upper()
        out.append(f"{const} = OperationSpec(")
        out.append(f"    name={py_str(op.op_id)},")
        out.append(f"    method={py_str(op.method)},")
        out.append(f"    path={py_str(op.path)},")
        path_params = [(p.name, p.py_name) for p in op.params if p.location == "path"]
        out.append(f"    path_params={tuple(path_params)!r},")
        query = tuple(p.name for p in op.params if p.location == "query")
        out.append(f"    query_params={query!r},")
        out.append(f"    has_body={op.has_body!r},")
        out.append(f"    idempotency={py_str(op.idempotency)},")
        out.append(f"    read_only={op.read_only!r},")
        out.append(f"    unwrap={op.envelope!r},")
        out.append(f"    response_kind={py_str(op.response_kind)},")
        out.append(")")
    out.append("")
    out.append("ALL = (")
    out.extend(f"    {op.op_id.upper()}," for op in ops)
    out.append(")")
    out.append("")
    return "\n".join(out)


def render_methods(ops: list[Operation]) -> str:
    type_names = sorted({op.result_type for op in ops} | collect_type_names(ops))
    out = [HEADER.rstrip(), "", '"""Generated API methods, mixed into Layrcake and AsyncLayrcake."""', ""]
    out.append("@@TYPING_IMPORT@@")
    out.append("")
    out.append("import httpx")
    out.append("")
    out.append("from .._response import LayrcakeResponse")
    out.append("from .._types import NOT_GIVEN, NotGiven")
    out.append("from . import operations as _ops")
    if type_names:
        out.append("from .types import (")
        out.extend(f"    {n}," for n in type_names)
        out.append(")")
    out.append("")
    out.append("if TYPE_CHECKING:")
    out.append("    from .._base import AsyncTransport, SyncTransport")
    out.append("")
    out.append('__all__ = ["AsyncMethods", "SyncMethods"]')
    for is_async in (False, True):
        out.append("")
        out.append("")
        cls = "AsyncMethods" if is_async else "SyncMethods"
        out.append(f"class {cls}:")
        out.append('    """The API operations, one method each. Generated from openapi.json."""')
        out.append("")
        transport = "AsyncTransport" if is_async else "SyncTransport"
        out.append(f'    _transport: "{transport}"')
        for op in ops:
            out.append("")
            out.extend(render_method(op, is_async))
    out.append("")
    return finish(out)


def collect_type_names(ops: list[Operation]) -> set[str]:
    names: set[str] = set()
    builtin = {
        "Any",
        "Dict",
        "List",
        "Literal",
        "Optional",
        "Union",
        "Sequence",
        "str",
        "int",
        "float",
        "bool",
        "None",
        "True",
        "False",
    }
    for op in ops:
        exprs = [p.annotation for p in op.params] + [op.result_type, op.live_type, op.dry_type]
        for expr in exprs:
            for tok in re.findall(r"[A-Za-z_][A-Za-z0-9_]*", re.sub(r'"[^"]*"', "", expr)):
                if tok not in builtin:
                    names.add(tok)
    return names


def signature(op: Operation, dry_run: str | None) -> list[str]:
    """The parameter lines of a method. dry_run replaces the dry_run annotation when set."""
    sig = ["        self,"]
    path_params = [p for p in op.params if p.location == "path"]
    others = [p for p in op.params if p.location != "path"]
    for p in path_params:
        sig.append(f"        {p.py_name}: str,")
    sig.append("        *,")
    required_dry = dry_run is not None and "=" not in dry_run
    for p in sorted(others, key=lambda x: not (x.required or (x.name == "dry_run" and required_dry))):
        if p.name == "dry_run" and dry_run is not None:
            sig.append(f"        dry_run: {dry_run},")
        elif p.required:
            sig.append(f"        {p.py_name}: {p.annotation},")
        else:
            sig.append(f"        {p.py_name}: Union[{p.annotation}, NotGiven] = NOT_GIVEN,")
    if op.idempotency != "none":
        sig.append("        idempotency_key: Union[str, NotGiven] = NOT_GIVEN,")
    sig.append("        extra_headers: Optional[Mapping[str, str]] = None,")
    sig.append("        extra_query: Optional[Mapping[str, Any]] = None,")
    if op.has_body:
        sig.append("        extra_body: Optional[Mapping[str, Any]] = None,")
    sig.append("        timeout: Union[float, httpx.Timeout, NotGiven, None] = NOT_GIVEN,")
    return sig


def render_method(op: Operation, is_async: bool) -> list[str]:
    lines: list[str] = []
    prefix = "async def" if is_async else "def"
    if op.dry_type:
        variants = [
            ("Literal[True]", op.dry_type),
            ("Union[Literal[False], NotGiven] = NOT_GIVEN", op.live_type),
            ("Union[bool, NotGiven] = NOT_GIVEN", op.result_type),
        ]
        for dry_annotation, returns in variants:
            lines.append("    @overload")
            lines.append(f"    {prefix} {op.op_id}(")
            lines.extend(signature(op, dry_annotation))
            lines.append(f"    ) -> LayrcakeResponse[{returns}]: ...")
            lines.append("")
    lines.append(f"    {prefix} {op.op_id}(")
    lines.extend(signature(op, None))
    lines.append(f"    ) -> LayrcakeResponse[{op.result_type}]:")
    lines.extend(render_docstring(op))
    path_params = [p for p in op.params if p.location == "path"]
    body_params = [p for p in op.params if p.location == "body"]
    query_params = [p for p in op.params if p.location == "query"]
    call = "await self._transport.request(" if is_async else "self._transport.request("
    lines.append(f"        return {call}")
    lines.append(f"            _ops.{op.op_id.upper()},")
    if path_params:
        lines.append(
            "            path_params={" + ", ".join(f"{py_str(p.name)}: {p.py_name}" for p in path_params) + "},"
        )
    if query_params:
        lines.append("            query={")
        lines.extend(f"                {py_str(p.name)}: {p.py_name}," for p in query_params)
        lines.append("            },")
    if op.has_body:
        if body_params:
            lines.append("            body={")
            lines.extend(f"                {py_str(p.name)}: {p.py_name}," for p in body_params)
            lines.append("            },")
        else:
            lines.append("            body={},")
        lines.append("            extra_body=extra_body,")
    if op.idempotency != "none":
        lines.append("            idempotency_key=idempotency_key,")
    lines.append("            extra_headers=extra_headers,")
    lines.append("            extra_query=extra_query,")
    lines.append("            timeout=timeout,")
    lines.append("        )")
    return lines


def render_docstring(op: Operation) -> list[str]:
    headline = op.headline
    out = [f'        """{doc_text(headline)}']
    rest = op.summary[len(headline) :].strip() if op.summary.startswith(headline) else op.summary
    for text in (rest, op.description):
        if text and text.strip() != headline:
            out.append("")
            out.extend(wrap(doc_text(text), 88, "        "))
    out.append("")
    out.append(f"        `{op.method} {op.path}`")
    if op.dry_type:
        out.append("")
        out.extend(
            wrap(
                "With dry_run=True the result is the call's plan and nothing is looked up, "
                "reserved or charged. The return type follows the flag.",
                88,
                "        ",
            )
        )
    documented = [p for p in op.params if p.description]
    if documented or op.idempotency != "none":
        out.append("")
        out.append("        Args:")
        for p in documented:
            first, *more = wrap(f"{p.py_name}: {doc_text(p.description)}", 88, "            ")
            out.append(first)
            out.extend("    " + r for r in more)
        if op.idempotency != "none":
            text = (
                "idempotency_key: Sent as the Idempotency-Key header. If omitted, the SDK generates "
                "one and reuses it on every automatic retry of this call."
            )
            first, *more = wrap(text, 88, "            ")
            out.append(first)
            out.extend("    " + r for r in more)
    out.append('        """')
    return out


def render_readme_table(ops: list[Operation]) -> str:
    rows = []
    for op in ops:
        args = [p.py_name for p in op.params if p.location == "path"]
        if any(p.location in ("body", "query") for p in op.params):
            args.append("**params")
        summary = op.headline.replace("|", "\\|")
        rows.append(f"| `{op.op_id}({', '.join(args)})` | `{op.method} {op.path}` | {summary} |")
    return "\n".join(
        [README_START, "", "| Method | Endpoint | What it does |", "| --- | --- | --- |", *rows, "", README_END]
    )


def splice_readme(readme: str, table: str) -> str:
    start = readme.find(README_START)
    end = readme.find(README_END)
    if start == -1 or end == -1 or end < start:
        raise SystemExit("README.md is missing the methods markers")
    return readme[:start] + table + readme[end + len(README_END) :]


def main() -> int:
    parser = argparse.ArgumentParser(description=(__doc__ or "").splitlines()[0])
    parser.add_argument("--check", action="store_true", help="fail if the generated files are stale")
    args = parser.parse_args()
    spec = json.loads(SPEC_PATH.read_text(encoding="utf-8"))
    raw_summaries = json.loads(SUMMARIES_PATH.read_text(encoding="utf-8"))
    summaries = {k: v for k, v in raw_summaries.items() if not k.startswith("_")}
    types_py, operations_py, methods_py, table = build(spec, summaries)
    files = {
        OUT_DIR / "__init__.py": HEADER,
        OUT_DIR / "types.py": types_py,
        OUT_DIR / "operations.py": operations_py,
        OUT_DIR / "methods.py": methods_py,
        README_PATH: splice_readme(README_PATH.read_text(encoding="utf-8"), table),
    }
    stale = [p for p, content in files.items() if not p.exists() or p.read_text(encoding="utf-8") != content]
    if args.check:
        if stale:
            for p in stale:
                print(f"stale: {p.relative_to(ROOT)}", file=sys.stderr)
            print("Generated code is out of date. Run: python scripts/generate.py", file=sys.stderr)
            return 1
        print("Generated code is up to date.")
        return 0
    OUT_DIR.mkdir(parents=True, exist_ok=True)
    for p, content in files.items():
        if p in stale:
            p.write_text(content, encoding="utf-8")
            print(f"wrote {p.relative_to(ROOT)}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
